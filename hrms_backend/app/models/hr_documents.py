"""Issued employee letters and company policies.

``EmployeeLetter`` is every letter on an employee's file — offer,
appointment, confirmation and so on — whether HR generated it from a
template (printed on the letterhead) or uploaded a signed copy. The
employee sees the ones marked visible in the app's Documents section.

``CompanyPolicy`` is a policy document (leave policy, code of conduct …)
that HR publishes to everyone.
"""
from __future__ import annotations

from datetime import date, datetime
from typing import Optional

from sqlalchemy import (
    Boolean,
    Date,
    DateTime,
    ForeignKey,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column

from .base import Base, TimestampMixin, mysql_table_args

LETTER_TYPES = (
    "offer",
    "appointment",
    "confirmation",
    "increment",
    "promotion",
    "experience",
    "relieving",
    "termination",
    "warning",
    "other",
)

POLICY_CATEGORIES = (
    "hr",
    "leave",
    "attendance",
    "conduct",
    "it",
    "travel",
    "safety",
    "other",
)


class EmployeeLetter(Base, TimestampMixin):
    __tablename__ = "employee_letters"
    __table_args__ = mysql_table_args

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    employee_id: Mapped[int] = mapped_column(
        ForeignKey("employees.id", ondelete="CASCADE"), nullable=False, index=True
    )
    letter_type: Mapped[str] = mapped_column(String(32), nullable=False)
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    letter_number: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)
    issued_on: Mapped[date] = mapped_column(Date, nullable=False)
    # "generated" (from a template, on the letterhead) | "uploaded"
    source: Mapped[str] = mapped_column(String(16), nullable=False)
    template_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("letter_templates.id", ondelete="SET NULL"), nullable=True
    )
    # Set when the row was carried over from an offer / confirmation
    # letter generated by the payroll flow (generated_documents).
    generated_document_id: Mapped[Optional[int]] = mapped_column(
        Integer, nullable=True, unique=True
    )
    file_key: Mapped[str] = mapped_column(String(500), nullable=False)
    file_name: Mapped[str] = mapped_column(String(255), nullable=False)
    mime_type: Mapped[str] = mapped_column(
        String(100), nullable=False, default="application/pdf"
    )
    file_size: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    visible_to_employee: Mapped[bool] = mapped_column(
        Boolean, default=True, nullable=False
    )
    notes: Mapped[Optional[str]] = mapped_column(String(500), nullable=True)
    # Removing a carried-over payroll letter only hides it here — the
    # generated_documents row stays for letter numbering / audit.
    is_removed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    issued_by: Mapped[Optional[int]] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )


class CompanyPolicy(Base, TimestampMixin):
    __tablename__ = "company_policies"
    __table_args__ = mysql_table_args

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    category: Mapped[str] = mapped_column(String(32), nullable=False, default="hr")
    description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    version: Mapped[Optional[str]] = mapped_column(String(32), nullable=True)
    effective_date: Mapped[Optional[date]] = mapped_column(Date, nullable=True)
    file_key: Mapped[str] = mapped_column(String(500), nullable=False)
    file_name: Mapped[str] = mapped_column(String(255), nullable=False)
    mime_type: Mapped[str] = mapped_column(
        String(100), nullable=False, default="application/pdf"
    )
    file_size: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    # Published policies are visible to every employee.
    is_published: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    # Employees confirm "I have read and accept" in the app.
    requires_acknowledgement: Mapped[bool] = mapped_column(
        Boolean, default=True, nullable=False
    )
    # Bumped when a new version of the document is uploaded, so everyone
    # accepts the new one.
    revision: Mapped[int] = mapped_column(Integer, default=1, nullable=False)
    uploaded_by: Mapped[Optional[int]] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )


class PolicyAcknowledgement(Base, TimestampMixin):
    """An employee's "I have read and accept" for one revision of a policy."""

    __tablename__ = "policy_acknowledgements"
    __table_args__ = (
        UniqueConstraint(
            "policy_id", "employee_id", "revision", name="uq_policy_ack"
        ),
        mysql_table_args,
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    policy_id: Mapped[int] = mapped_column(
        ForeignKey("company_policies.id", ondelete="CASCADE"), nullable=False, index=True
    )
    employee_id: Mapped[int] = mapped_column(
        ForeignKey("employees.id", ondelete="CASCADE"), nullable=False, index=True
    )
    revision: Mapped[int] = mapped_column(Integer, nullable=False)
    acknowledged_at: Mapped[datetime] = mapped_column(DateTime, nullable=False)
